//! Recovery plan builder. Given a freshly observed btrfs filesystem
//! identity, current-root identity, and source-snapshot identity,
//! produce an immutable [`RecoveryPlan`] with a confirmation token
//! bound to the plan id and the identity fields.
//!
//! Pure (no I/O): the caller supplies the observations. This keeps the
//! plan builder testable without a real btrfs image.

use std::time::{SystemTime, UNIX_EPOCH};

use crate::model::recovery::{
    BootFinalizationDecision, BootLayout, BtrfsFilesystemIdentity, BtrfsSubvolumeIdentity,
    CatosIdentity, FstabRootDefinition, RecoveryError, RecoveryPlan, RECOVERY_PLAN_SCHEMA_VERSION,
};

/// Inputs to [`build_plan`]. Everything the builder needs to produce a
/// complete plan; no I/O is performed inside the builder.
#[derive(Debug, Clone)]
pub struct PlanInputs {
    /// Newly observed filesystem identity (FSID + major:minor).
    pub filesystem: BtrfsFilesystemIdentity,
    /// Newly observed current-root subvolume identity.
    pub current_root: BtrfsSubvolumeIdentity,
    /// Newly observed source-snapshot identity.
    pub source_snapshot: BtrfsSubvolumeIdentity,
    /// Resolved boot layout of the source snapshot.
    pub boot_layout: BootLayout,
    /// CatOS identity of the source snapshot (os-release-derived).
    pub catos_identity: Option<CatosIdentity>,
    /// Root fstab line the recovered root will mount.
    pub fstab_root_definition: FstabRootDefinition,
    /// Operator-facing id of the plan. Generated by the caller; must be
    /// unique enough to identify this recovery for the lifetime of the
    /// filesystem.
    pub plan_id: String,
    /// Optional hostname / kernel string for human context.
    pub generated_on_host: Option<String>,
    /// Caller-supplied entropy mixed into the confirmation token. The
    /// caller is responsible for sourcing it (e.g. from
    /// `/dev/urandom`, `getrandom(2)`, or a UUIDv4 generator).
    pub confirmation_token_entropy: Vec<u8>,
}

/// Build a plan. Pure function of the inputs; performs no I/O.
///
/// The confirmation token is a deterministic, opaque base16 string
/// mixed from the plan id, the filesystem identity, the source
/// snapshot identity, and the caller-supplied entropy. It is NOT
/// cryptographic — we have no OpenSSL by design — but it is bound
/// structurally to the plan id and identity fields, so it cannot be
/// replayed against a different plan without being detected by
/// [`crate::recovery::identity::verify_confirmation_token`].
pub fn build_plan(inputs: PlanInputs) -> Result<RecoveryPlan, RecoveryError> {
    use crate::recovery::identity::SubvolumePath;

    // Validate the paths so a malformed plan never reaches disk.
    SubvolumePath::parse(&inputs.current_root.path)?;
    SubvolumePath::parse(&inputs.source_snapshot.path)?;

    if inputs.current_root.path == inputs.source_snapshot.path {
        return Err(RecoveryError::new(
            crate::model::recovery::RecoveryErrorKind::TargetChanged,
            "current root and source snapshot are the same path",
        ));
    }
    if !inputs.source_snapshot.read_only {
        return Err(RecoveryError::new(
            crate::model::recovery::RecoveryErrorKind::SnapshotNotReadonly,
            "source snapshot is not readonly; refusing to plan",
        ));
    }
    if inputs.plan_id.is_empty() {
        return Err(RecoveryError::new(
            crate::model::recovery::RecoveryErrorKind::StateRecordCorrupt,
            "plan_id must not be empty",
        ));
    }
    if inputs.confirmation_token_entropy.len() < 16 {
        return Err(RecoveryError::new(
            crate::model::recovery::RecoveryErrorKind::StateRecordCorrupt,
            "confirmation token entropy must be at least 16 bytes",
        ));
    }

    let transaction_id = inputs.plan_id.clone();
    let backup_root_path = format!(
        "{}/{transaction_id}/root-before",
        crate::model::recovery::TransactionPaths::backups_dir()
    );
    let staging_root_path = format!(
        "{}/{transaction_id}/new-root",
        crate::model::recovery::TransactionPaths::staging_dir()
    );

    let finalization = decide_finalization(&inputs.boot_layout);

    let mut refusal_conditions = Vec::new();
    refusal_conditions.push("plan id, filesystem FSID, or subvolume identity has changed".into());
    refusal_conditions
        .push("the source snapshot's readonly flag has been cleared between plan and apply".into());
    refusal_conditions.push("the recovery would operate on the currently running root".into());
    refusal_conditions
        .push("another transaction is already active for this btrfs filesystem".into());
    refusal_conditions.push(
        "the configured backup or staging path is already occupied by a foreign object".into(),
    );
    if matches!(finalization, BootFinalizationDecision::RequiredUnavailable) {
        refusal_conditions.push(
            "boot finalization is required but no stable CatOS bootloadu interface is available"
                .into(),
        );
    }

    let mut risks_and_warnings = Vec::new();
    risks_and_warnings.push(format!(
        "the original root will be preserved as a readonly snapshot at {backup_root_path}; \
         it will not be deleted automatically"
    ));
    risks_and_warnings.push(format!(
        "the source snapshot at {} will remain readonly and will not be modified",
        inputs.source_snapshot.path
    ));
    if matches!(finalization, BootFinalizationDecision::RequiredAvailable) {
        risks_and_warnings.push(
            "boot resources will be reconciled after the root switch by invoking the CatOS \
             bootloadu interface at a fixed trusted path"
                .into(),
        );
    }

    let predicted_steps = vec![
        "preflight".into(),
        "acquire_lock".into(),
        "create_backup".into(),
        "create_replacement".into(),
        "swap_roots".into(),
        "verify_new_root".into(),
        if matches!(finalization, BootFinalizationDecision::RequiredAvailable) {
            "finalize_boot".into()
        } else {
            "skip_finalize_boot".into()
        },
        "verify_final".into(),
        "complete".into(),
    ];

    let confirmation_token = build_confirmation_token(
        &inputs.plan_id,
        &inputs.filesystem.fsid,
        inputs.current_root.subvolume_id,
        inputs.source_snapshot.subvolume_id,
        &inputs.confirmation_token_entropy,
    );

    let generated_at_unix = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    Ok(RecoveryPlan {
        schema_version: RECOVERY_PLAN_SCHEMA_VERSION,
        plan_id: inputs.plan_id,
        generated_at_unix,
        generated_on_host: inputs.generated_on_host,
        filesystem: inputs.filesystem,
        current_root: inputs.current_root,
        source_snapshot: inputs.source_snapshot,
        target_catos_identity: inputs.catos_identity,
        boot_layout: inputs.boot_layout,
        finalization,
        backup_root_path,
        staging_root_path,
        fstab_root_definition: inputs.fstab_root_definition,
        predicted_steps,
        refusal_conditions,
        risks_and_warnings,
        confirmation_token,
        evidence: Vec::new(),
    })
}

/// Decide whether boot finalization is required, and if so whether a
/// stable CatOS bootloadu interface is available.
fn decide_finalization(layout: &BootLayout) -> BootFinalizationDecision {
    if layout.boot_inside_root
        && !layout.boot_separate_filesystem
        && !layout.boot_separate_subvolume
        && layout.esp_device.is_none()
    {
        return BootFinalizationDecision::NotRequired;
    }
    if layout.bootloadu_detected {
        BootFinalizationDecision::RequiredAvailable
    } else {
        BootFinalizationDecision::RequiredUnavailable
    }
}

/// Build the confirmation token string. The format is `v1:<plan_id>:<token>`,
/// where `<token>` is a base16 digest mixed from the plan id, identity
/// fields, and the caller-supplied entropy. The prefix lets future
/// versions change the algorithm without ambiguity.
pub fn build_confirmation_token(
    plan_id: &str,
    fsid: &str,
    current_root_subvolid: u64,
    source_snapshot_subvolid: u64,
    entropy: &[u8],
) -> String {
    let mut state = FnvBuilder::new();
    state = state.mix_str("catos-recovery-v1");
    state = state.mix_str(plan_id);
    state = state.mix_str(fsid);
    state = state.mix_u64(current_root_subvolid);
    state = state.mix_u64(source_snapshot_subvolid);
    state = state.mix_bytes(entropy);
    let digest = state.finish();
    format!("v1:{plan_id}:{digest:016x}")
}

/// Minimal FNV-1a 64-bit hasher used for confirmation tokens. We use a
/// tiny inline implementation rather than pulling in a `fnv` or `xxhash`
/// crate: this is NOT a security primitive — it only needs to mix
/// inputs uniformly and be deterministic.
struct FnvBuilder {
    h: u64,
}

impl FnvBuilder {
    const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
    const FNV_PRIME: u64 = 0x0000_0100_0000_01b3;

    fn new() -> Self {
        FnvBuilder {
            h: Self::FNV_OFFSET,
        }
    }

    fn mix_str(mut self, s: &str) -> Self {
        for b in s.as_bytes() {
            self.h ^= *b as u64;
            self.h = self.h.wrapping_mul(Self::FNV_PRIME);
        }
        // Mix in a separator so prefixes cannot collide.
        self.h ^= 0x1f as u64;
        self.h = self.h.wrapping_mul(Self::FNV_PRIME);
        self
    }

    fn mix_bytes(mut self, bytes: &[u8]) -> Self {
        for b in bytes {
            self.h ^= *b as u64;
            self.h = self.h.wrapping_mul(Self::FNV_PRIME);
        }
        self.h ^= 0x1f as u64;
        self.h = self.h.wrapping_mul(Self::FNV_PRIME);
        self
    }

    fn mix_u64(mut self, v: u64) -> Self {
        for shift in (0..64).step_by(8) {
            self.h ^= ((v >> shift) & 0xff) as u64;
            self.h = self.h.wrapping_mul(Self::FNV_PRIME);
        }
        self.h ^= 0x1f as u64;
        self.h = self.h.wrapping_mul(Self::FNV_PRIME);
        self
    }

    fn finish(self) -> u64 {
        self.h
    }
}

