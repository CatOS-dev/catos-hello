//! Recovery plan builder. Given a freshly observed btrfs filesystem
//! identity, current-root identity, and source-snapshot identity,
//! produce an immutable [`RecoveryPlan`] with a confirmation token
//! bound to the plan id and the identity fields.
//!
//! Pure (no I/O): the caller supplies the observations. This keeps the
//! plan builder testable without a real btrfs image.

use std::time::{SystemTime, UNIX_EPOCH};

use serde::Serialize;
use sha2::{Digest, Sha256};

use crate::shared::model::recovery::{
    BootConsistencyReport, BootConsistencyStatus, BootLayout, BtrfsFilesystemIdentity,
    BtrfsSubvolumeIdentity, CatosIdentity, FstabRootDefinition, RecoveryError, RecoveryPlan,
    RECOVERY_PLAN_SCHEMA_VERSION,
};

/// Inputs to [`build_plan`]. Everything the builder needs to produce a
/// complete plan; no I/O is performed inside the builder.
#[derive(Debug, Clone)]
pub struct PlanInputs {
    /// Newly observed filesystem identity (FSID + major:minor).
    pub filesystem: BtrfsFilesystemIdentity,
    /// Newly observed current-root subvolume identity.
    pub current_root: BtrfsSubvolumeIdentity,
    /// Newly observed source-snapshot identity.
    pub source_snapshot: BtrfsSubvolumeIdentity,
    /// Resolved boot layout of the source snapshot.
    pub boot_layout: BootLayout,
    /// CatOS identity of the source snapshot (os-release-derived).
    pub catos_identity: Option<CatosIdentity>,
    /// Root fstab line the recovered root will mount.
    pub fstab_root_definition: FstabRootDefinition,
    /// Operator-facing id of the plan. Generated by the caller; must be
    /// unique enough to identify this recovery for the lifetime of the
    /// filesystem.
    pub plan_id: String,
    /// Optional hostname / kernel string for human context.
    pub generated_on_host: Option<String>,
    /// Caller-supplied entropy mixed into the confirmation token. The
    /// caller is responsible for sourcing it (e.g. from
    /// `/dev/urandom`, `getrandom(2)`, or a UUIDv4 generator).
    pub confirmation_token_entropy: Vec<u8>,
}

/// Build a plan. Pure function of the inputs; performs no I/O.
///
/// The confirmation token is a deterministic, opaque base16 string
/// mixed from the plan id, the filesystem identity, the source
/// snapshot identity, and the caller-supplied entropy. It is NOT
/// cryptographic — we have no OpenSSL by design — but it is bound
/// structurally to the plan id and identity fields, so it cannot be
/// replayed against a different plan without being detected by
/// [`crate::shared::snapshot_engine::identity::verify_confirmation_token`].
pub fn build_plan(inputs: PlanInputs) -> Result<RecoveryPlan, RecoveryError> {
    use crate::shared::snapshot_engine::identity::{ensure_supported_snapshot_layout, SubvolumePath};

    // Validate the paths so a malformed plan never reaches disk.
    SubvolumePath::parse(&inputs.current_root.path)?;
    SubvolumePath::parse(&inputs.source_snapshot.path)?;

    if inputs.current_root.path == inputs.source_snapshot.path {
        return Err(RecoveryError::new(
            crate::shared::model::recovery::RecoveryErrorKind::TargetChanged,
            "current root and source snapshot are the same path",
        ));
    }
    if !inputs.source_snapshot.read_only {
        return Err(RecoveryError::new(
            crate::shared::model::recovery::RecoveryErrorKind::SnapshotNotReadonly,
            "source snapshot is not readonly; refusing to plan",
        ));
    }
    ensure_supported_snapshot_layout(&inputs.current_root.path, &inputs.source_snapshot.path)?;
    crate::shared::snapshot_engine::identity::validate_recovery_id(&inputs.plan_id)?;
    if inputs.confirmation_token_entropy.len() != 32 {
        return Err(RecoveryError::new(
            crate::shared::model::recovery::RecoveryErrorKind::RandomSourceFailed,
            "confirmation nonce must contain exactly 32 random bytes",
        ));
    }

    let transaction_id = inputs.plan_id.clone();
    let backup_root_path = format!(
        "{}/{transaction_id}/root-before",
        crate::shared::model::recovery::TransactionPaths::backups_dir()
    );
    let staging_root_path = format!(
        "{}/{transaction_id}/new-root",
        crate::shared::model::recovery::TransactionPaths::staging_dir()
    );

    let boot_consistency =
        crate::shared::snapshot_engine::boot::evaluate_readonly_consistency(&inputs.boot_layout);
    let mut refusal_conditions = vec![
        "plan id, filesystem FSID, or subvolume identity has changed".into(),
        "the source snapshot's readonly flag has been cleared between plan and apply".into(),
        "the recovery would operate on the currently running root".into(),
        "another transaction is already active for this btrfs filesystem".into(),
        "the configured backup or staging path is already occupied by a foreign object".into(),
    ];
    if boot_consistency.status != BootConsistencyStatus::Consistent {
        refusal_conditions.push(format!(
            "boot consistency gate is {:?}: {}",
            boot_consistency.status,
            boot_consistency.reasons.join("; ")
        ));
    }

    let mut risks_and_warnings = Vec::new();
    risks_and_warnings.push(format!(
        "the original root will be preserved as a readonly snapshot at {backup_root_path}; \
         it will not be deleted automatically"
    ));
    risks_and_warnings.push(format!(
        "the source snapshot at {} will remain readonly and will not be modified",
        inputs.source_snapshot.path
    ));
    risks_and_warnings.push(
        "recovery swaps the root subvolume only; it does NOT update any bootloader, ESP, \
         UKI, or initramfs. Boot resources outside the root subvolume are NOT reconciled."
            .into(),
    );

    let predicted_steps = vec![
        "preflight".into(),
        "acquire_lock".into(),
        "create_backup".into(),
        "create_replacement".into(),
        "swap_roots".into(),
        "verify_new_root".into(),
        "verify_final".into(),
        "complete".into(),
    ];

    let generated_at_unix = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    let nonce = hex_encode(&inputs.confirmation_token_entropy);
    let mut plan = RecoveryPlan {
        schema_version: RECOVERY_PLAN_SCHEMA_VERSION,
        plan_id: inputs.plan_id,
        generated_at_unix,
        generated_on_host: inputs.generated_on_host,
        filesystem: inputs.filesystem,
        current_root: inputs.current_root,
        source_snapshot: inputs.source_snapshot,
        target_catos_identity: inputs.catos_identity,
        boot_layout: inputs.boot_layout,
        boot_consistency,
        backup_root_path,
        staging_root_path,
        fstab_root_definition: inputs.fstab_root_definition,
        predicted_steps,
        refusal_conditions,
        risks_and_warnings,
        nonce,
        plan_digest: String::new(),
        confirmation_token: String::new(),
        evidence: Vec::new(),
    };
    plan.plan_digest = effective_plan_digest(&plan)?;
    plan.confirmation_token =
        build_confirmation_token(&plan.plan_id, &plan.plan_digest, &plan.nonce);
    Ok(plan)
}

#[derive(Serialize)]
struct CanonicalEffectivePlan<'a> {
    schema_version: u32,
    plan_id: &'a str,
    filesystem: &'a BtrfsFilesystemIdentity,
    current_root: &'a BtrfsSubvolumeIdentity,
    source_snapshot: &'a BtrfsSubvolumeIdentity,
    target_catos_identity: &'a Option<CatosIdentity>,
    boot_layout: &'a BootLayout,
    boot_consistency: &'a BootConsistencyReport,
    backup_root_path: &'a str,
    staging_root_path: &'a str,
    fstab_root_definition: &'a FstabRootDefinition,
    predicted_steps: &'a [String],
    refusal_conditions: &'a [String],
    risks_and_warnings: &'a [String],
}

/// Hash the canonical execution-relevant plan. The persisted digest,
/// nonce, confirmation token, timestamps, host label, and evidence are
/// deliberately excluded so re-serialising JSON with a different field
/// order cannot alter the effective plan while preserving an old digest.
pub fn effective_plan_digest(plan: &RecoveryPlan) -> Result<String, RecoveryError> {
    let canonical = CanonicalEffectivePlan {
        schema_version: plan.schema_version,
        plan_id: &plan.plan_id,
        filesystem: &plan.filesystem,
        current_root: &plan.current_root,
        source_snapshot: &plan.source_snapshot,
        target_catos_identity: &plan.target_catos_identity,
        boot_layout: &plan.boot_layout,
        boot_consistency: &plan.boot_consistency,
        backup_root_path: &plan.backup_root_path,
        staging_root_path: &plan.staging_root_path,
        fstab_root_definition: &plan.fstab_root_definition,
        predicted_steps: &plan.predicted_steps,
        refusal_conditions: &plan.refusal_conditions,
        risks_and_warnings: &plan.risks_and_warnings,
    };
    let bytes = serde_json::to_vec(&canonical).map_err(|error| {
        RecoveryError::new(
            crate::shared::model::recovery::RecoveryErrorKind::StateRecordCorrupt,
            format!("cannot serialise canonical recovery plan: {error}"),
        )
    })?;
    Ok(hex_encode(&Sha256::digest(bytes)))
}

/// Build the confirmation token from the immutable plan digest and
/// kernel-generated nonce. The token format is
/// `v2:<plan_id>:<sha256>`.
pub fn build_confirmation_token(plan_id: &str, plan_digest: &str, nonce: &str) -> String {
    let mut digest = Sha256::new();
    digest.update(b"catos-recovery-confirmation-v2\0");
    digest.update(plan_id.as_bytes());
    digest.update(b"\0");
    digest.update(plan_digest.as_bytes());
    digest.update(b"\0");
    digest.update(nonce.as_bytes());
    format!("v2:{plan_id}:{}", hex_encode(&digest.finalize()))
}

/// Build the explicit-revert confirmation token. Unlike the apply
/// token, this token is bound to the transaction's current state and
/// the freshly observed filesystem FSID, so a token copied from an
/// earlier status response cannot authorize a later or different
/// revert.
pub fn build_revert_confirmation_token(
    transaction_id: &str,
    plan_digest: &str,
    filesystem_fsid: &str,
    state: &str,
    nonce: &str,
) -> String {
    let mut digest = Sha256::new();
    digest.update(b"catos-recovery-revert-confirmation-v1\0");
    digest.update(transaction_id.as_bytes());
    digest.update(b"\0");
    digest.update(plan_digest.as_bytes());
    digest.update(b"\0");
    digest.update(filesystem_fsid.as_bytes());
    digest.update(b"\0");
    digest.update(state.as_bytes());
    digest.update(b"\0");
    digest.update(nonce.as_bytes());
    format!(
        "revert-v1:{transaction_id}:{}",
        hex_encode(&digest.finalize())
    )
}

pub fn verify_revert_confirmation_token(
    transaction_id: &str,
    plan_digest: &str,
    filesystem_fsid: &str,
    state: &str,
    nonce: &str,
    presented: &str,
) -> Result<(), RecoveryError> {
    let expected =
        build_revert_confirmation_token(transaction_id, plan_digest, filesystem_fsid, state, nonce);
    if presented != expected {
        return Err(RecoveryError::new(
            crate::shared::model::recovery::RecoveryErrorKind::ConfirmationTokenMismatch,
            "revert confirmation token is not bound to the current transaction state",
        ));
    }
    Ok(())
}

fn hex_encode(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut output = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        output.push(HEX[(byte >> 4) as usize] as char);
        output.push(HEX[(byte & 0x0f) as usize] as char);
    }
    output
}

